import assert from 'node:assert/strict';
import {createRequire} from 'node:module';
import {loadSource} from './load-source.mjs';
const THREE=createRequire(import.meta.url)('three');
const {createDarkAura}=loadSource('src/scene/effects/darkAura.ts');
const {createAuraOutlineField}=loadSource('src/scene/effects/auraOutlineField.ts');
const field=createAuraOutlineField([new THREE.Vector2(-.2,0),new THREE.Vector2(.2,0),new THREE.Vector2(.2,1),new THREE.Vector2(-.2,1)]);
const sample=(x,y)=>{
 const {width,height,data}=field.texture.image,r=field.rect;
 return data[Math.floor((y-r.y)/r.w*height)*width+Math.floor((x-r.x)/r.z*width)];
};
assert.ok(sample(0,.5)<128,'Cached field must identify the interior');
assert.ok(sample(.3,.5)>128,'Cached field must identify the exterior');
field.texture.dispose();
const {createBankaiPresence}=loadSource('src/scene/bankaiPresence.ts');
const v=(x,y,z)=>new THREE.Vector3(x,y,z);
const aura=createDarkAura(12);
aura.setShapes([{start:v(0,.2,0),end:v(0,.8,0),startRadius:.1,endRadius:.05}]);
aura.update(2,.5);
const proxy=aura.group.children[0];
assert.equal(aura.group.visible,true);
assert.equal(proxy.material.depthWrite,false);
assert.equal(proxy.material.blending,THREE.NormalBlending);
aura.setShapes([]);aura.update(2);assert.equal(aura.group.visible,false);
assert.throws(()=>aura.setShapes(Array(13).fill({})),RangeError);
aura.setOutline([new THREE.Vector2(-.2,0),new THREE.Vector2(.2,0),new THREE.Vector2(0,1)]);
aura.update(2);assert.equal(aura.group.visible,true,'An outline must render without capsules');
assert.equal(proxy.material.uniforms.outlineCount.value,3);
assert.throws(()=>aura.setOutline([new THREE.Vector2()]),RangeError);
aura.setOutline(null);aura.update(2);assert.equal(aura.group.visible,false);
aura.dispose();aura.dispose();
const scene=new THREE.Scene(),presence=createBankaiPresence(scene),grip=v(0,1,0);
presence.configure({x:0,z:0},grip);
const group=scene.children[0],mesh=group.children[0];
const snapshot=()=>JSON.stringify({start:mesh.material.uniforms.shapeStart.value.map(x=>x.toArray()),end:mesh.material.uniforms.shapeEnd.value.map(x=>x.toArray()),time:mesh.material.uniforms.time.value,opacity:mesh.material.uniforms.opacity.value});
presence.update(.1,grip,-3);
const held=mesh.material.uniforms.shapeEnd.value[7];
const actual=v(held.x,held.y,held.z).applyMatrix4(group.matrixWorld);
assert.ok(actual.distanceTo(grip)<1e-8,'Release tendril must contact the actual sword grip');
presence.update(2,v(0,-4,0),-1);const first=snapshot();
presence.update(10,v(0,-30,0),8);presence.update(2,v(0,-4,0),-1);
assert.equal(snapshot(),first,'Backward seek must reproduce pose and volume state');
presence.update(12,v(0,-30,0),9);assert.equal(group.visible,false);
presence.update(0,grip,-4);assert.equal(group.visible,true,'Replay must restore aura');
presence.hide();assert.equal(group.visible,false);
presence.dispose();assert.equal(scene.children.length,0);
console.log('Dark aura: grip contact, seek/replay, bounds visibility, and disposal checks passed.');
